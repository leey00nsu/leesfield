import { act, renderHook } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import type { PropsWithChildren } from "react";
import { afterEach, expect, it, vi } from "vitest";
import { mediaAssetKeys, useMediaAssetList, usePatchAssetMetadata } from "./use-media-assets";
import { getMediaAsset, patchAssetMetadata } from "../api/media-asset-api";
import type { MediaAssetDto } from "@/shared/media-assets/media-asset-contract";
vi.mock("../api/media-asset-api", () => ({ getMediaAsset: vi.fn(), patchAssetMetadata: vi.fn() }));
afterEach(() => { vi.useRealTimers(); vi.clearAllMocks(); });
it("recovers a result lookup after transient retries are exhausted without starting a generation", async () => {
  vi.useFakeTimers();
  vi.mocked(getMediaAsset).mockRejectedValueOnce(new Error("offline"))
    .mockResolvedValue({ id: "late", url: "/late.png" } as Awaited<ReturnType<typeof getMediaAsset>>);
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const wrapper = ({ children }: PropsWithChildren) => <QueryClientProvider client={client}>{children}</QueryClientProvider>;
  const view = renderHook(() => useMediaAssetList(["late"]), { wrapper });
  await act(async () => { await vi.advanceTimersByTimeAsync(1); });
  expect(view.result.current[0].isError).toBe(true);
  await act(async () => { await vi.advanceTimersByTimeAsync(15_000); });
  expect(view.result.current[0].data?.url).toBe("/late.png");
  expect(getMediaAsset).toHaveBeenCalledTimes(2);
  view.unmount();
  client.clear();
});
it("updates the same asset across cached lists while preserving other cards and refreshing starred filters", async () => {
  const target = { id: "target", version: 1, starred: false } as MediaAssetDto;
  const other = { id: "other", version: 2, starred: true } as MediaAssetDto;
  const saved = { ...target, version: 2, starred: true };
  vi.mocked(patchAssetMetadata).mockResolvedValue(saved);
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const allKey = mediaAssetKeys.list("image", undefined, { sort: "latest" });
  const starredKey = mediaAssetKeys.list("image", undefined, { sort: "latest", starred: true });
  client.setQueryData(allKey, { pages: [{ items: [target, other], nextCursor: null }], pageParams: [null] });
  client.setQueryData(starredKey, { pages: [{ items: [other], nextCursor: null }], pageParams: [null] });
  const wrapper = ({ children }: PropsWithChildren) => <QueryClientProvider client={client}>{children}</QueryClientProvider>;
  const hook = renderHook(usePatchAssetMetadata, { wrapper });
  await act(async () => { await hook.result.current.mutateAsync({ id: target.id, expectedVersion: 1, starred: true }); });
  const result = client.getQueryData<{ pages: { items: MediaAssetDto[] }[] }>(allKey)!;
  expect(result.pages[0].items[0]).toEqual(saved);
  expect(result.pages[0].items[1]).toBe(other);
  expect(client.getQueryData(mediaAssetKeys.detail(target.id))).toEqual(saved);
  expect(client.getQueryState(allKey)?.isInvalidated).toBe(false);
  expect(client.getQueryState(starredKey)?.isInvalidated).toBe(true);
  hook.unmount(); client.clear();
});
