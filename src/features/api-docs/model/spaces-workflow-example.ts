/** Node.js 20+; the caller supplies a model with a compatible image input port. */
export const spacesWorkflowExample = [
  'import { readFile } from "node:fs/promises";',
  'const base = process.env.API_BASE_URL;',
  'const key = process.env.API_KEY;',
  'const modelId = process.env.MODEL_ID;',
  'async function api(path, method = "GET", body, retryKey) {',
  '  const response = await fetch(base + "/api/external" + path, {',
  '    method, headers: { "X-API-Key": key, "Content-Type": "application/json",',
  '      ...(retryKey ? { "Idempotency-Key": retryKey } : {}) },',
  '    ...(body === undefined ? {} : { body: JSON.stringify(body) }),',
  '  });',
  '  const result = response.status === 204 ? null : await response.json();',
  '  if (!response.ok) throw new Error(JSON.stringify(result));',
  '  return result;',
  '}',
  'await api("/spaces/capabilities");',
  'await api("/spaces/models?type=image");',
  'const schema = await api("/spaces/models/" + encodeURIComponent(modelId) + "/schema");',
  'const inputPort = schema.files.find(file => file.portId)?.portId;',
  'if (!inputPort) throw new Error("Choose an image model with an image input port");',
  'const values = {}; // Fill required non-file inputs from schema.inputSchema.',
  'const parameters = {};',
  'for (const [name, value] of Object.entries(values)) {',
  '  const path = schema.inputSchema.properties[name]?.["x-node-config-path"];',
  '  if (path?.startsWith("parameters.dynamicParams.")) {',
  '    (parameters.dynamicParams ??= {})[path.slice("parameters.dynamicParams.".length)] = value;',
  '  } else if (path?.startsWith("parameters.")) parameters[path.slice("parameters.".length)] = value;',
  '} // Prompt uses config.prompt; files use asset-backed graph edges.',
  'const bytes = await readFile("./reference.png");',
  'const { upload } = await api("/assets/uploads", "POST", {',
  '  intendedType: "image", fileName: "reference.png", declaredMimeType: "image/png", declaredBytes: bytes.length,',
  '});',
  'const transfer = await fetch(new URL(upload.upload.url, base), {',
  '  method: "PUT", headers: { ...upload.upload.headers, "X-API-Key": key }, body: bytes,',
  '});',
  'if (!transfer.ok) throw new Error("Upload failed: " + transfer.status);',
  'const { asset } = await api("/assets/uploads/" + upload.id + "/confirm", "POST", {});',
  'let { space } = await api("/spaces", "POST", { title: "API image chain" });',
  'const node = (id, kind, config, x) => ({ id, kind, config, position: { x, y: 0 },',
  '  configVersion: 1, selectedOutputAssetId: null });',
  'const edge = (id, from, to, sourcePortId, targetPortId) => ({ id, sourceNodeId: from,',
  '  targetNodeId: to, sourcePortId, targetPortId, sortOrder: 0 });',
  'const imageConfig = prompt => ({ prompt, modelKey: schema.model.key, parameters });',
  '({ space } = await api("/spaces/" + space.id, "PUT", {',
  '  schemaVersion: 3, expectedVersion: space.version, title: space.title, groups: [], selectionChanges: [],',
  '  nodes: [node("source", "input.image", { assetId: asset.id }, 0),',
  '    node("first", "generate.image", imageConfig("A quiet forest"), 300),',
  '    node("next", "generate.image", imageConfig("Add warm evening light"), 600),',
  '    node("view", "output.single", { mediaType: "image" }, 900)],',
  '  edges: [edge("input", "source", "first", "image", inputPort),',
  '    edge("reuse", "first", "next", "image", inputPort),',
  '    edge("display", "next", "view", "image", "image")],',
  '}));',
  'async function run(nodeId) {',
  '  const path = "/spaces/" + space.id + "/nodes/" + nodeId + "/executions";',
  '  const body = { expectedGraphVersion: space.version };',
  '  const retryKey = crypto.randomUUID(); // Reuse this key AND body if submission is retried.',
  '  let { execution } = await api(path, "POST", body, retryKey);',
  '  for (let attempt = 0; attempt < 300; attempt++) {',
  '    if (["completed", "failed", "cancelled"].includes(execution.status)) break;',
  '    await new Promise(resolve => setTimeout(resolve, 2000));',
  '    ({ execution } = await api(path + "/" + execution.executionId));',
  '  }',
  '  if (execution.status !== "completed") throw new Error(execution.errorCode ?? execution.status);',
  '  return execution;',
  '}',
  'const first = await run("first");',
  '({ space } = await api("/spaces/" + space.id));',
  '({ space } = await api("/spaces/" + space.id, "PUT", {',
  '  schemaVersion: 3, expectedVersion: space.version, title: space.title, groups: space.groups,',
  '  nodes: space.nodes.map(n => n.id === "first" ? { ...n, selectedOutputAssetId: first.outputAssetIds[0] } : n),',
  '  edges: space.edges, selectionChanges: ["first"],',
  '}));',
  'await run("next"); // Explicit second call; no graph scheduler.',
  'const { output } = await api("/spaces/" + space.id + "/nodes/view/output");',
  'console.log(output, new URL("/spaces/" + space.id, base).href);',
].join("\n");
